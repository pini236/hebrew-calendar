// The widget's ribbon moves with the app's silk physics (src/components/silk.ts): a home-screen widget
// can't run code, so the motion is rendered here into frames, and the widget plays
// them with a ViewFlipper (a still ribbon, then a gust that settles back to rest).
// Writes android/app/src/main/res/drawable{,-night}-nodpi/widget_ribbon_fNN.png and puts the flipper
// in the widget layouts in place of the static ribbon.
// Run: node scripts/build-widget-ribbon.mjs
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createServer } from 'vite';

const { chromium } = createRequire(import.meta.url)('playwright');

const RES = 'android/app/src/main/res';
const W = 10; // ribbon width, dp (as the static widget ribbon)
const L = 18; // ribbon length, dp
const PAD = 6; // room to swing, each side, dp
const BOX_W = W + PAD * 2;
const BOX_H = L + 4;
const SCALE = 4; // xxxhdpi
const FPS = 11; // frames per second the flipper plays (interval below)
const INTERVAL = Math.round(1000 / FPS);
const REST = 40; // still frames before each gust (~3.6 s)
const MAX_GUST = 48; // at most this many moving frames (~4.4 s)
// One set of frames: the widget follows the app's colour scheme, not the phone's, so a night-qualified
// resource set would show the wrong frames; the saffron is the same on both papers.
const THEMES = [['', '#E3A73A', '#FFFEFB']];

const server = await createServer({ server: { port: 5199, strictPort: true }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto('http://localhost:5199/');

let frameCount = 0;
for (const [suffix, ribbon, paper] of THEMES) {
  const frames = await page.evaluate(
    async ({ W, L, PAD, BOX_W, BOX_H, SCALE, FPS, MAX_GUST, ribbon, paper }) => {
      const m = await import('/src/components/silk.ts');
      const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
      const lum = (c) => 0.2126 * m.srgbToLinear(c[0]) + 0.7152 * m.srgbToLinear(c[1]) + 0.0722 * m.srgbToLinear(c[2]);
      const look = { base: hex(ribbon).map(m.srgbToLinear), dark: lum(hex(paper)) < 0.2 };
      const sim = new m.SilkSim({ width: W, length: L, segments: 8, seed: 20261120 });
      sim.settle?.();
      const cv = document.createElement('canvas');
      cv.width = BOX_W * SCALE;
      cv.height = BOX_H * SCALE;
      const ctx = cv.getContext('2d');
      const shot = () => {
        ctx.setTransform(1, 0, 0, 1, 0, 0);
        ctx.clearRect(0, 0, cv.width, cv.height);
        m.paintSilk(ctx, sim, look, { ox: PAD + W / 2, oy: 2, dpr: SCALE, sub: 3, strips: 4, sheen: 0.8, shadow: true, tuck: 2 });
        return cv.toDataURL('image/png');
      };
      const out = [shot()]; // the ribbon at rest
      sim.gust(0.9);
      for (let i = 0; i < MAX_GUST; i++) {
        sim.advance(1 / FPS);
        out.push(shot());
        if (i > 8 && sim.asleep) break;
      }
      out.push(out[0]); // back to rest, seamless
      return out;
    },
    { W, L, PAD, BOX_W, BOX_H, SCALE, FPS, MAX_GUST, ribbon, paper },
  );
  const dir = `${RES}/drawable${suffix}-nodpi`;
  mkdirSync(dir, { recursive: true });
  for (const f of readdirSync(dir)) if (/^widget_ribbon_f\d+\.png$/.test(f)) rmSync(`${dir}/${f}`);
  frames.forEach((d, i) => writeFileSync(`${dir}/widget_ribbon_f${String(i).padStart(2, '0')}.png`, Buffer.from(d.split(',')[1], 'base64')));
  frameCount = frames.length;
  console.log(`${dir}: ${frames.length} frames`);
}
await browser.close();
await server.close();

// the flipper: frame 0 shown REST times (a still ribbon), then the gust. It replaces the static ribbon
// in every widget layout (inline: widget layouts are safest without <include>).
const seq = [...Array(REST).fill(0), ...Array.from({ length: frameCount - 1 }, (_, i) => i + 1)];
const flipper = (marginRight) => `<ViewFlipper
        android:id="@+id/w_ribbon"
        android:layout_width="${BOX_W}dp"
        android:layout_height="${BOX_H}dp"
        android:layout_gravity="top|right"
        android:layout_marginRight="${marginRight}dp"
        android:autoStart="true"
        android:flipInterval="${INTERVAL}"
        android:importantForAccessibility="no">
        <!-- generated by scripts/build-widget-ribbon.mjs: the app's silk ribbon, played as frames -->
${seq.map((f) => `        <ImageView android:layout_width="${BOX_W}dp" android:layout_height="${BOX_H}dp" android:src="@drawable/widget_ribbon_f${String(f).padStart(2, '0')}" />`).join('\n')}
    </ViewFlipper>`;
for (const f of readdirSync(`${RES}/layout`).filter((n) => /^widget_(xs|s|m_short|m|l)\.xml$/.test(n))) {
  const path = `${RES}/layout/${f}`;
  let x = readFileSync(path, 'utf8');
  // first run: the static ImageView (its margin is the ribbon's edge; the frames add PAD on each side)
  x = x.replace(/<ImageView\s+android:id="@\+id\/w_ribbon"[\s\S]*?android:layout_marginRight="(\d+)dp"[\s\S]*?\/>/, (_, m) => flipper(+m - PAD));
  // later runs: the flipper itself
  x = x.replace(/<ViewFlipper\s+android:id="@\+id\/w_ribbon"[\s\S]*?android:layout_marginRight="(\d+)dp"[\s\S]*?<\/ViewFlipper>/, (_, m) => flipper(+m));
  writeFileSync(path, x);
}
// the Omer widget's layouts: the flipper sits on the day in the field (its size and place are set in code), so only
// its frames are refreshed here
for (const f of readdirSync(`${RES}/layout`).filter((n) => /^omer_widget_\w+\.xml$/.test(n))) {
  const path = `${RES}/layout/${f}`;
  const x = readFileSync(path, 'utf8').replace(
    /(<ViewFlipper\s+android:id="@\+id\/w_ribbon"[\s\S]*?-->\n)([ ]*)<ImageView[\s\S]*?(\s*<\/ViewFlipper>)/,
    (_, head, pad, tail) =>
      head + seq.map((n) => `${pad}<ImageView android:layout_width="match_parent" android:layout_height="match_parent" android:src="@drawable/widget_ribbon_f${String(n).padStart(2, '0')}" />`).join('\n') + tail,
  );
  writeFileSync(path, x);
}
console.log(`layouts: ${seq.length} frames each, ${INTERVAL} ms (${((seq.length * INTERVAL) / 1000).toFixed(1)} s loop)`);
